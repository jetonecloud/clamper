"""The notification: plain text, five things, in this order.

1. What crossed — the spend and the threshold.
2. Which limit.
3. What was clamped.
4. What was **not**, and why.
5. The exact `clamper release` command to undo it.

Written for the person reading it at 3am who did not write the config, may
not have Clamper installed, and needs the shortest path from "something
stopped" to "I have put it back". So the release command is in the message
rather than in a link, and it names a clamp id — generated by Clamper, shape
`[a-z0-9-]` — never a resource name, because it is the one string in this
tool somebody will paste into a shell.

Resource ids appear; tag values never do, because tags are free text and
people put things in them. Control characters are stripped from everything.
"""

from __future__ import annotations

from clamper.core.report import model
from clamper.core.report.text import clean, hourly, percent, plural

#: SNS's limit on a subject line.
SUBJECT_LIMIT = 100

#: Lines listed per section before "and N more". An email with four hundred
#: lines is one nobody reads to the end, and the end is where the release
#: command is.
SECTION_LIMIT = 25


def subject(report: model.Report) -> str:
    prefix = f"[clamper {report.stack_name}]"
    if report.over_cap:
        body = f"over budget, {len(report.not_acted)} targets held: above the cap"
    elif report.stopped_count:
        body = f"stopped {plural(report.stopped_count, 'resource')}"
        if report.attention:
            body += f", {len(report.attention)} NOT stopped"
    elif report.count(model.WOULD_CLAMP):
        body = f"dry-run: would stop {plural(report.count(model.WOULD_CLAMP), 'resource')}"
    elif report.attention or report.errors:
        body = "needs attention: something could not be checked or stopped"
    elif report.breached:
        body = "over budget, nothing left to stop"
    elif report.warned:
        body = f"{report.warned[0].id} at {percent(report.warned[0].percent)} of its limit"
    else:
        body = "status"
    return clean(f"{prefix} {body}")[:SUBJECT_LIMIT]


def body(report: model.Report) -> str:
    out: list[str] = []

    # 1 and 2: what crossed, and which limit.
    for limit in report.limits:
        out.append(
            f"Limit {limit.id} ({limit.scope}): {limit.level.upper()} - {clean(limit.reason)}"
        )
    if report.dry_run:
        out.append("")
        out.append("Mode is dry-run. NOTHING WAS STOPPED. Below is what would have been.")

    # 3: clamped.
    stopped = [line for line in report.acted if line.status in model.STOPPED]
    would = [line for line in report.acted if line.status == model.WOULD_CLAMP]
    if stopped:
        out += ["", f"STOPPED ({len(stopped)}):"]
        out += _section(stopped)
    if would:
        out += ["", f"WOULD STOP in enforce mode ({len(would)}):"]
        out += _section(would)

    # 4: not clamped, and why.
    if report.not_acted:
        out += ["", f"NOT STOPPED ({len(report.not_acted)}) - still costing money:"]
        out += _section(report.not_acted)
    if report.over_cap:
        out += [
            "",
            f"Nothing was stopped: {len(report.not_acted)} targets is above "
            f"max_actions_per_run ({report.cap}). That is more likely a stray tag than a "
            f"real need, so Clamper waits for a person. Raise the cap, or run "
            f"`clamper clamp --yes` if you mean it.",
        ]
    if report.errors:
        out += ["", "COULD NOT CHECK:"]
        out += [f"  - {clean(error)}" for error in report.errors]

    # 5: undo.
    if report.release_command:
        out += [
            "",
            "To put everything back:",
            f"    {report.release_command}",
            "or one resource at a time with `clamper release <clamp-id> --target <id>`.",
        ]
    out += [
        "",
        f"Stack {report.stack_name}, {report.generated_at}, by {clean(report.actor) or 'clamper'}.",
        "Figures are indicative list prices for ranking, not a bill.",
    ]
    return "\n".join(out) + "\n"


def _section(lines: tuple[model.Line, ...] | list[model.Line]) -> list[str]:
    out: list[str] = []
    for line in list(lines)[:SECTION_LIMIT]:
        text = (
            f"  - {line.title} {clean(line.target_id)} ({line.region}), {hourly(line.hourly_usd)}"
        )
        if line.detail:
            text += f": {clean(line.detail)}"
        out.append(text)
    if len(lines) > SECTION_LIMIT:
        out.append(f"  ... and {len(lines) - SECTION_LIMIT} more (see `clamper status`)")
    return out


__all__ = ["body", "subject"]
