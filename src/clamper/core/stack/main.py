"""The main stack: budgets, topics, ledger, enforcer, schedule.

What is in it, in dependency order:

- **Two SNS topics.** `alerts` is where Budgets publishes and only the
  enforcer subscribes. `notifications` is where the enforcer publishes and
  people subscribe. Two, not one, because the enforcer is subscribed to the
  alerts topic: if it published there, every notification would trigger
  another reconcile.
- **The alerts topic policy** AWS documents for Budgets, with both
  `aws:SourceAccount` and `aws:SourceArn`. Without the first, the topic is
  publishable by the Budgets service on behalf of any account.
- **One budget per limit**, each with a warn and a clamp notification to the
  alerts topic. Plain notifications, not budget actions: the first two
  action-enabled budgets are free and each one after is $0.10 a day, and
  budget actions cannot scale an Auto Scaling group to zero or write a
  ledger anyway.
- **The ledger table.** On-demand, point-in-time recovery on, the `by-status`
  index, and `Retain` on delete and replace. No TTL attribute: the ledger is
  never pruned.
- **The enforcer's role**, trusting `lambda.amazonaws.com` only with an
  `aws:SourceAccount` condition, carrying the policy `core/policy.py`
  generates and nothing else.
- **The log group**, 30 days' retention, created before the function so
  Lambda does not create one that keeps logs forever.
- **The function**, its two invoke permissions, and the **EventBridge
  schedule** — the primary guarantee, since AWS sends an `ACTUAL` alert only
  once per budget per period.

Both topics are unencrypted, on purpose, and the template says so in the
resources' metadata. Budgets cannot publish to an encrypted topic without a
customer-managed KMS key whose policy grants it, and such a key costs
$1/month — more than the rest of Clamper's running cost combined. The topics
carry thresholds and resource ids, not credentials; the threat model covers
what that exposes.
"""

from __future__ import annotations

import json
from typing import Any

from clamper.core.config import (
    NOTIFICATION_ACTUAL,
    Config,
    Limit,
)
from clamper.core.names import StackNames
from clamper.core.policy import enforcer_policy
from clamper.core.stack import FORMAT_VERSION, get_att, ref, render, sub, substitute

#: The Lambda runtime. Pinned rather than "latest", because the zip carries
#: a pure-Python PyYAML built for it and a runtime change is a change
#: somebody should test.
RUNTIME = "python3.12"

HANDLER = "clamper.enforcer.handler.handler"

#: Five minutes. A reconcile touching fifty resources with adaptive retries
#: against a throttled API takes a while; Lambda's three-second default would
#: kill it partway and leave pending entries.
TIMEOUT_SECONDS = 300

MEMORY_MB = 256

LOG_RETENTION_DAYS = 30

#: What the schedule's event carries, so the enforcer can tell a scheduled
#: run from a Budgets alert without parsing anything from SNS.
SCHEDULE_INPUT = {"source": "clamper.schedule"}

HEADER = """
Clamper main stack: budgets, the enforcer, its ledger, and its schedule.

Generated by `clamper deploy` from clamper.yml and actions.yml. Plain
CloudFormation, no macros, no transforms: what you read is what deploys.

The enforcer's IAM policy below is generated from actions.yml. It cannot
terminate or delete anything, has no iam, cloudformation or sts permission,
and scopes every write to the managed tag. See iam/README.md.
"""

UNENCRYPTED_TOPIC = (
    "Unencrypted on purpose. Budgets cannot publish to an encrypted topic without a "
    "customer-managed KMS key whose policy grants it, which costs $1/month - more than "
    "the rest of Clamper. The topic carries thresholds and resource ids, not credentials."
)


def template(config: Config) -> dict[str, Any]:
    names = StackNames(config.stack_name)
    policy = enforcer_policy(config, "${AWS::AccountId}", region="${AWS::Region}")

    resources: dict[str, Any] = {
        "AlertsTopic": {
            "Type": "AWS::SNS::Topic",
            "Metadata": {"Clamper": UNENCRYPTED_TOPIC},
            "Properties": {
                "TopicName": names.alerts_topic,
                "Tags": [{"Key": "clamper:component", "Value": "alerts"}],
            },
        },
        "AlertsTopicPolicy": {
            "Type": "AWS::SNS::TopicPolicy",
            "Properties": {
                "Topics": [ref("AlertsTopic")],
                "PolicyDocument": {
                    "Version": "2012-10-17",
                    "Statement": [
                        {
                            "Sid": "AllowBudgetsFromThisAccountOnly",
                            "Effect": "Allow",
                            "Principal": {"Service": "budgets.amazonaws.com"},
                            "Action": "SNS:Publish",
                            "Resource": ref("AlertsTopic"),
                            "Condition": {
                                "StringEquals": {"aws:SourceAccount": ref("AWS::AccountId")},
                                "ArnLike": {
                                    "aws:SourceArn": sub(
                                        "arn:${AWS::Partition}:budgets::${AWS::AccountId}:*"
                                    )
                                },
                            },
                        }
                    ],
                },
            },
        },
        "NotificationsTopic": {
            "Type": "AWS::SNS::Topic",
            "Metadata": {"Clamper": UNENCRYPTED_TOPIC},
            "Properties": {
                "TopicName": names.topic,
                "Tags": [{"Key": "clamper:component", "Value": "notifications"}],
            },
        },
    }

    if config.notifications.email:
        resources["NotificationsEmail"] = {
            "Type": "AWS::SNS::Subscription",
            "Metadata": {
                "Clamper": (
                    "AWS sends a confirmation email. Until somebody clicks it, nothing is "
                    "delivered - `clamper doctor` reports an unconfirmed subscription as a "
                    "failure, because it is a clamp nobody will hear about."
                )
            },
            "Properties": {
                "TopicArn": ref("NotificationsTopic"),
                "Protocol": "email",
                "Endpoint": config.notifications.email,
            },
        }

    for limit in config.limits:
        resources[_budget_id(limit)] = _budget(config, limit)

    resources.update(
        {
            "Ledger": {
                "Type": "AWS::DynamoDB::Table",
                "DeletionPolicy": "Retain",
                "UpdateReplacePolicy": "Retain",
                "Metadata": {
                    "Clamper": (
                        "The record of everything Clamper stopped and what it was before. "
                        "Retained on stack deletion: without it, nothing can be released. "
                        "No TTL - it is never pruned."
                    )
                },
                "Properties": {
                    "TableName": names.table,
                    "BillingMode": "PAY_PER_REQUEST",
                    "AttributeDefinitions": [
                        {"AttributeName": "pk", "AttributeType": "S"},
                        {"AttributeName": "sk", "AttributeType": "S"},
                        {"AttributeName": "status", "AttributeType": "S"},
                        {"AttributeName": "created_at", "AttributeType": "S"},
                    ],
                    "KeySchema": [
                        {"AttributeName": "pk", "KeyType": "HASH"},
                        {"AttributeName": "sk", "KeyType": "RANGE"},
                    ],
                    "GlobalSecondaryIndexes": [
                        {
                            "IndexName": "by-status",
                            "KeySchema": [
                                {"AttributeName": "status", "KeyType": "HASH"},
                                {"AttributeName": "created_at", "KeyType": "RANGE"},
                            ],
                            "Projection": {"ProjectionType": "ALL"},
                        }
                    ],
                    "PointInTimeRecoverySpecification": {"PointInTimeRecoveryEnabled": True},
                    "SSESpecification": {"SSEEnabled": True},
                    "Tags": [{"Key": "clamper:component", "Value": "ledger"}],
                },
            },
            "EnforcerRole": {
                "Type": "AWS::IAM::Role",
                "Properties": {
                    "RoleName": names.role,
                    "Description": "Clamper enforcer. Generated from actions.yml.",
                    "AssumeRolePolicyDocument": {
                        "Version": "2012-10-17",
                        "Statement": [
                            {
                                "Effect": "Allow",
                                "Principal": {"Service": "lambda.amazonaws.com"},
                                "Action": "sts:AssumeRole",
                                "Condition": {
                                    "StringEquals": {"aws:SourceAccount": ref("AWS::AccountId")}
                                },
                            }
                        ],
                    },
                    "Policies": [
                        {"PolicyName": "clamper-enforcer", "PolicyDocument": substitute(policy)}
                    ],
                    "Tags": [{"Key": "clamper:component", "Value": "enforcer"}],
                },
            },
            "EnforcerLogs": {
                "Type": "AWS::Logs::LogGroup",
                "Properties": {
                    "LogGroupName": names.log_group,
                    "RetentionInDays": LOG_RETENTION_DAYS,
                },
            },
            "Enforcer": {
                "Type": "AWS::Lambda::Function",
                "DependsOn": ["EnforcerLogs"],
                "Properties": {
                    "FunctionName": names.function,
                    "Description": "Clamper enforcer: reads Budgets, decides, records, acts.",
                    "Runtime": RUNTIME,
                    "Handler": HANDLER,
                    "Role": get_att("EnforcerRole", "Arn"),
                    "Timeout": TIMEOUT_SECONDS,
                    "MemorySize": MEMORY_MB,
                    "Code": {"S3Bucket": ref("ArtifactBucket"), "S3Key": ref("ArtifactKey")},
                    "Environment": {
                        "Variables": {
                            "CLAMPER_STACK_NAME": config.stack_name,
                            "CLAMPER_LEDGER_TABLE": ref("Ledger"),
                            "CLAMPER_TOPIC_ARN": ref("NotificationsTopic"),
                            "CLAMPER_STACK_RESOURCES": {
                                "Fn::Join": [
                                    ",",
                                    [
                                        names.function,
                                        ref("Ledger"),
                                        ref("AlertsTopic"),
                                        ref("NotificationsTopic"),
                                        ref("EnforcerRole"),
                                        names.schedule,
                                        ref("ArtifactBucket"),
                                    ],
                                ]
                            },
                        }
                    },
                    "Tags": [{"Key": "clamper:component", "Value": "enforcer"}],
                },
            },
            "EnforcerAlertsSubscription": {
                "Type": "AWS::SNS::Subscription",
                "Properties": {
                    "TopicArn": ref("AlertsTopic"),
                    "Protocol": "lambda",
                    "Endpoint": get_att("Enforcer", "Arn"),
                },
            },
            "EnforcerInvokeFromAlerts": {
                "Type": "AWS::Lambda::Permission",
                "Properties": {
                    "FunctionName": ref("Enforcer"),
                    "Action": "lambda:InvokeFunction",
                    "Principal": "sns.amazonaws.com",
                    "SourceArn": ref("AlertsTopic"),
                    "SourceAccount": ref("AWS::AccountId"),
                },
            },
            "ReconcileSchedule": {
                "Type": "AWS::Events::Rule",
                "Metadata": {
                    "Clamper": (
                        "The primary guarantee, not a nicety. AWS sends an ACTUAL budget alert "
                        "once per budget per period, so SNS alone would be one chance a month."
                    )
                },
                "Properties": {
                    "Name": names.schedule,
                    "Description": "Clamper reconcile: re-read Budgets and enforce.",
                    "ScheduleExpression": _rate(config.safety.reconcile_hours),
                    "State": "ENABLED",
                    "Targets": [
                        {
                            "Id": "enforcer",
                            "Arn": get_att("Enforcer", "Arn"),
                            "Input": json.dumps(SCHEDULE_INPUT),
                        }
                    ],
                },
            },
            "EnforcerInvokeFromSchedule": {
                "Type": "AWS::Lambda::Permission",
                "Properties": {
                    "FunctionName": ref("Enforcer"),
                    "Action": "lambda:InvokeFunction",
                    "Principal": "events.amazonaws.com",
                    "SourceArn": get_att("ReconcileSchedule", "Arn"),
                },
            },
        }
    )

    return {
        "AWSTemplateFormatVersion": FORMAT_VERSION,
        "Description": (
            f"Clamper ({config.stack_name}): hard spending limits. Mode at deploy time: "
            f"{config.mode}."
        ),
        "Parameters": {
            "ArtifactBucket": {
                "Type": "String",
                "Description": "The bootstrap stack's bucket, holding the enforcer zip.",
            },
            "ArtifactKey": {
                "Type": "String",
                "Description": "The enforcer zip's key. Content-addressed, so a new config "
                "or a new version is a new key and the function updates.",
            },
        },
        "Resources": resources,
        "Outputs": {
            "LedgerTable": {"Value": ref("Ledger")},
            "NotificationsTopic": {"Value": ref("NotificationsTopic")},
            "AlertsTopic": {"Value": ref("AlertsTopic")},
            "EnforcerFunction": {"Value": ref("Enforcer")},
        },
    }


def _budget_id(limit: Limit) -> str:
    return "Budget" + "".join(part.capitalize() for part in limit.id.split("-"))


def _budget(config: Config, limit: Limit) -> dict[str, Any]:
    """One cost budget, two notifications, both to the alerts topic.

    Changing a threshold replaces the budget rather than editing it —
    `NotificationsWithSubscribers` is "Update requires: Replacement" — so a
    budget's history resets when its thresholds change. Worth knowing before
    you wonder why.
    """
    budget: dict[str, Any] = {
        "BudgetName": limit.budget_name(config.stack_name),
        "BudgetType": "COST",
        "TimeUnit": "MONTHLY",
        "BudgetLimit": {"Amount": _amount(limit.amount_usd), "Unit": "USD"},
    }
    if limit.scope.cost_filter:
        budget["CostFilters"] = limit.scope.cost_filter
    clamp_type = "ACTUAL" if limit.notification_type == NOTIFICATION_ACTUAL else "FORECASTED"
    subscriber = [{"SubscriptionType": "SNS", "Address": ref("AlertsTopic")}]
    wanted = [("ACTUAL", limit.warn_percent), (clamp_type, limit.clamp_percent)]
    # A warn threshold equal to the clamp threshold is a valid config and an
    # invalid budget: Budgets rejects two identical notifications.
    unique = list(dict.fromkeys(wanted))
    return {
        "Type": "AWS::Budgets::Budget",
        "DependsOn": ["AlertsTopicPolicy"],
        "Properties": {
            "Budget": budget,
            "NotificationsWithSubscribers": [
                {
                    "Notification": {
                        "NotificationType": kind,
                        "ComparisonOperator": "GREATER_THAN",
                        "Threshold": threshold,
                        "ThresholdType": "PERCENTAGE",
                    },
                    "Subscribers": subscriber,
                }
                for kind, threshold in unique
            ],
        },
    }


def _amount(value: float) -> float | int:
    return int(value) if float(value).is_integer() else round(value, 2)


def _rate(hours: int) -> str:
    return "rate(1 hour)" if hours == 1 else f"rate({hours} hours)"


def render_template(config: Config) -> str:
    return render(template(config), HEADER)
