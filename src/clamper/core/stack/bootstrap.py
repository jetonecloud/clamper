"""The bootstrap stack: one bucket for the enforcer's deployment zip.

Versioned, SSE-S3, every public-access block on, bucket-owner-enforced
ownership, TLS required by policy, and old versions expired after 30 days so
redeploys do not accumulate zips forever. `Retain` on delete, because
CloudFormation cannot delete a bucket that still holds objects and a failed
stack deletion is a worse experience than a leftover empty bucket.
"""

from __future__ import annotations

from typing import Any

from clamper.core.stack import FORMAT_VERSION, get_att, ref, render, sub

HEADER = """
Clamper bootstrap stack: the S3 bucket that holds the enforcer's code.

Generated by `clamper deploy`. Plain CloudFormation, no macros, no
transforms. It creates one bucket and one bucket policy, and nothing else.
"""


def template(stack_name: str) -> dict[str, Any]:
    return {
        "AWSTemplateFormatVersion": FORMAT_VERSION,
        "Description": f"Clamper bootstrap ({stack_name}): deployment artifact bucket.",
        "Resources": {
            "ArtifactBucket": {
                "Type": "AWS::S3::Bucket",
                "DeletionPolicy": "Retain",
                "UpdateReplacePolicy": "Retain",
                "Properties": {
                    "VersioningConfiguration": {"Status": "Enabled"},
                    "BucketEncryption": {
                        "ServerSideEncryptionConfiguration": [
                            {"ServerSideEncryptionByDefault": {"SSEAlgorithm": "AES256"}}
                        ]
                    },
                    "PublicAccessBlockConfiguration": {
                        "BlockPublicAcls": True,
                        "BlockPublicPolicy": True,
                        "IgnorePublicAcls": True,
                        "RestrictPublicBuckets": True,
                    },
                    "OwnershipControls": {"Rules": [{"ObjectOwnership": "BucketOwnerEnforced"}]},
                    "LifecycleConfiguration": {
                        "Rules": [
                            {
                                "Id": "expire-old-enforcer-zips",
                                "Status": "Enabled",
                                "NoncurrentVersionExpiration": {"NoncurrentDays": 30},
                                "AbortIncompleteMultipartUpload": {"DaysAfterInitiation": 1},
                            }
                        ]
                    },
                    "Tags": [{"Key": "clamper:component", "Value": "artifacts"}],
                },
            },
            "ArtifactBucketPolicy": {
                "Type": "AWS::S3::BucketPolicy",
                "Properties": {
                    "Bucket": ref("ArtifactBucket"),
                    "PolicyDocument": {
                        "Version": "2012-10-17",
                        "Statement": [
                            {
                                "Sid": "DenyInsecureTransport",
                                "Effect": "Deny",
                                "Principal": "*",
                                "Action": "s3:*",
                                "Resource": [
                                    get_att("ArtifactBucket", "Arn"),
                                    sub("${ArtifactBucket.Arn}/*"),
                                ],
                                "Condition": {"Bool": {"aws:SecureTransport": "false"}},
                            }
                        ],
                    },
                },
            },
        },
        "Outputs": {
            "ArtifactBucket": {
                "Description": "Where `clamper deploy` uploads the enforcer zip.",
                "Value": ref("ArtifactBucket"),
            }
        },
    }


def render_template(stack_name: str) -> str:
    return render(template(stack_name), HEADER)
